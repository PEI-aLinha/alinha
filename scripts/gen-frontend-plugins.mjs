#!/usr/bin/env node
// Generates frontend/shell/src/plugins.generated.ts from the submodules under
// plugins/<kind>/<id>/frontend. Runs automatically before dev/build/typecheck.
// Adding a plugin = adding the submodule; the shell is never edited by hand.
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = 'frontend/src/index.ts'

const dirs = (p) => (existsSync(p) ? readdirSync(p).filter((d) => statSync(join(p, d)).isDirectory()).sort() : [])

/**
 * Plugins under `pluginsDir` (<kind>/<id>) that have a frontend entry, sorted by kind then id.
 * `empty` lists plugin folders with nothing in them: a submodule that was never initialised.
 * A plugin without a frontend (backend-only) is neither registered nor reported.
 */
export function findPluginFrontends(pluginsDir) {
  const entries = []
  const empty = []
  for (const kind of dirs(pluginsDir)) {
    for (const id of dirs(join(pluginsDir, kind))) {
      const dir = join(pluginsDir, kind, id)
      const entry = join(dir, ENTRY)
      if (existsSync(entry)) entries.push({ id, kind, entry })
      else if (readdirSync(dir).length === 0) empty.push(`${kind}/${id}`)
    }
  }
  return { entries, empty }
}

/** Source of plugins.generated.ts, importing each entry relative to `outFile`. */
export function renderPluginsModule(entries, outFile) {
  const toImport = (p) => relative(dirname(outFile), p).split('\\').join('/')
  return [
    '// GENERATED by scripts/gen-frontend-plugins.mjs — do not edit.',
    "import type { FrontendPlugin } from '@alinha/plugin-sdk'",
    ...entries.map((e, i) => `import p${i} from '${toImport(e.entry)}'`),
    '',
    `export const plugins: FrontendPlugin[] = [${entries.map((_, i) => `p${i}`).join(', ')}]`,
    '',
  ].join('\n')
}

function main() {
  const outFile = join(root, 'frontend/shell/src/plugins.generated.ts')
  const { entries, empty } = findPluginFrontends(join(root, 'plugins'))
  for (const p of empty) console.warn(`! plugins/${p} is empty — missing "git submodule update --init"?`)
  writeFileSync(outFile, renderPluginsModule(entries, outFile))
  console.log(`plugins.generated.ts: ${entries.length} plugin(s) — ${entries.map((e) => e.id).join(', ') || 'none'}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
